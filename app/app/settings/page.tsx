import Link from "next/link";
import { count, eq } from "drizzle-orm";
import { Page } from "@/components/page";
import { AccountForms } from "@/components/settings/account-forms";
import { AiTest } from "@/components/settings/ai-test";
import { DataActions } from "@/components/settings/data-actions";
import { ProfileForm } from "@/components/settings/profile-form";
import { ThemePicker } from "@/components/theme";
import { aiStatus } from "@/lib/ai/provider";
import { CANDIDATE_PROMPT_VERSION, EVALUATOR_PROMPT_VERSION } from "@/lib/ai/prompts";
import { db } from "@/lib/db";
import { practiceSession } from "@/lib/db/schema";
import { fmtDate } from "@/lib/format";
import { requireOnboarded } from "@/lib/session";

export const metadata = { title: "Settings" };

const TABS = [["profile", "Practice profile"], ["account", "Account"], ["appearance", "Appearance"], ["ai", "AI service"], ["data", "Data and privacy"]] as const;
type Tab = (typeof TABS)[number][0];

export default async function Settings({ searchParams }: { searchParams: Promise<{ tab?: string }> }) {
  const { user, profile } = await requireOnboarded();
  const q = (await searchParams).tab;
  const tab: Tab = TABS.find(([id]) => id === q)?.[0] ?? "profile";

  return (
    <Page title="Settings" description="Your practice profile, account, look and data.">
      <nav aria-label="Settings sections" className="-mt-2 mb-8 flex gap-1 overflow-x-auto border-b border-line">
        {TABS.map(([id, label]) => (
          <Link key={id} href={`/app/settings?tab=${id}`} replace scroll={false} aria-current={tab === id ? "page" : undefined}
            className={`-mb-px whitespace-nowrap border-b-2 px-3 py-2.5 text-sm font-medium ${tab === id ? "border-accent text-accent" : "border-transparent text-muted hover:text-ink"}`}>{label}</Link>
        ))}
      </nav>

      {tab === "profile" && <ProfileForm defaults={{ level: profile.level, hiringFocus: profile.hiringFocus, seniority: profile.seniority, focusAreas: profile.focusAreas, difficulty: profile.difficulty }} />}
      {tab === "account" && <AccountForms name={user.name} email={user.email} joined={fmtDate(user.createdAt, true)} />}
      {tab === "appearance" && (
        <section aria-labelledby="theme-h"><h2 id="theme-h" className="font-serif text-xl">Theme</h2>
          <p className="mb-4 mt-1 text-sm text-muted">System follows your device. Your choice is saved in this browser.</p>
          <ThemePicker /></section>
      )}
      {tab === "ai" && <AiSection />}
      {tab === "data" && <DataSection userId={user.id} />}
    </Page>
  );
}

function AiSection() {
  const s = aiStatus();
  const rows: [string, string][] = [
    ["Provider", s.label],
    ["Model", s.model],
    ...(s.live ? [["Endpoint", s.host] as [string, string]] : []),
    ["Candidate prompt", CANDIDATE_PROMPT_VERSION],
    ["Evaluator prompt", EVALUATOR_PROMPT_VERSION],
  ];
  return (
    <section aria-labelledby="ai-h" className="max-w-xl">
      <h2 id="ai-h" className="font-serif text-xl">AI service</h2>
      <p className="mt-1 text-sm text-muted">
        {s.live ? "Candidates and reports are generated by a live model through Nine Router."
          : s.forcedMock ? "AI_PROVIDER is set to mock, so the built-in mock candidate is running."
          : "No AI_API_KEY is set, so the built-in mock candidate is running."}
      </p>
      <dl className="mt-5 divide-y divide-line rounded-lg border border-line bg-surface text-sm">
        {rows.map(([k, v]) => <div key={k} className="flex justify-between gap-4 px-4 py-2.5"><dt className="text-muted">{k}</dt><dd className="min-w-0 truncate font-medium">{v}</dd></div>)}
        <div className="flex justify-between gap-4 px-4 py-2.5"><dt className="text-muted">Status</dt><dd className={`font-medium ${s.live ? "text-accent" : "text-caution"}`}>{s.live ? "Live" : "Mock"}</dd></div>
      </dl>
      <p className="mt-3 text-xs text-muted">Configured with AI_BASE_URL, AI_API_KEY and AI_MODEL on the server. The key is never shown here.</p>
      <div className="mt-5"><AiTest live={s.live} /></div>
    </section>
  );
}

async function DataSection({ userId }: { userId: string }) {
  const [{ n }] = await db.select({ n: count() }).from(practiceSession).where(eq(practiceSession.userId, userId));
  return <DataActions sessionCount={n} />;
}
